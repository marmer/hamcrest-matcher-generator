package foo.bar.sample.assertj.lines;

public class Line {
    private final String sku;
    private final int quantity;

    public Line(final String sku, final int quantity) {
        this.sku = sku;
        this.quantity = quantity;
    }

    public String getSku() {
        return sku;
    }

    public int getQuantity() {
        return quantity;
    }
}
