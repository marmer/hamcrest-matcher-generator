package example.hamcrest.model;

public class Address {
    private final String street;
    private final String city;

    public Address(final String street, final String city) {
        this.street = street;
        this.city = city;
    }

    public String getStreet() {
        return street;
    }

    public String getCity() {
        return city;
    }
}
